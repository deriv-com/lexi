import type { BuildTaskStatus, MilestoneStatus, ProgrammeStatus } from "@lexi/contracts";
import { ALL_PROGRAMME_STATUSES, ProgrammeStateMachine } from "../programme-state-machine";
import { ALL_MILESTONE_STATUSES, MilestoneStateMachine } from "../milestone-state-machine";
import { ALL_BUILD_TASK_STATUSES, BuildTaskStateMachine } from "../build-task-state-machine";

/**
 * Derives the programme lifecycle graphs from the **live** state machines —
 * the `work-item-graph.ts` pattern, for the same reason: a hand-drawn
 * diagram silently drifts from the adjacency list it claims to describe.
 *
 * All three machines render into ONE marker-delimited section of
 * `PROGRAMME_LIFECYCLE.md`, regenerated by `npm run graph:programme` and
 * drift-checked with `--check`.
 */

interface MachineView<S extends string> {
  title: string;
  states: S[];
  edges: Array<{ from: S; to: S }>;
  terminalStates: S[];
  guard: string;
}

function view<S extends string>(
  title: string,
  states: S[],
  nextStates: (from: S) => S[],
  isTerminal: (state: S) => boolean,
  guard: string,
): MachineView<S> {
  const edges: Array<{ from: S; to: S }> = [];
  for (const from of states) {
    for (const to of nextStates(from)) {
      edges.push({ from, to });
    }
  }
  return { title, states, edges, terminalStates: states.filter(isTerminal), guard };
}

export function buildProgrammeGraphViews(): Array<MachineView<string>> {
  const programme = new ProgrammeStateMachine();
  const milestone = new MilestoneStateMachine();
  const buildTask = new BuildTaskStateMachine();

  return [
    view<ProgrammeStatus>(
      "Programme",
      [...ALL_PROGRAMME_STATUSES],
      (from) => programme.nextStates(from),
      (state) => programme.isTerminal(state),
      "ProgrammeStateMachine.assertTransition",
    ),
    view<MilestoneStatus>(
      "Milestone",
      [...ALL_MILESTONE_STATUSES],
      (from) => milestone.nextStates(from),
      (state) => milestone.isTerminal(state),
      "MilestoneStateMachine.assertTransition",
    ),
    view<BuildTaskStatus>(
      "Build task",
      [...ALL_BUILD_TASK_STATUSES],
      (from) => buildTask.nextStates(from),
      (state) => buildTask.isTerminal(state),
      "BuildTaskStateMachine.assertTransition",
    ),
  ] as Array<MachineView<string>>;
}

function renderMachine(machine: MachineView<string>): string {
  const lines: string[] = [];
  lines.push(`### ${machine.title}`);
  lines.push("");
  lines.push("```mermaid");
  lines.push("flowchart TD");
  for (const edge of machine.edges) {
    lines.push(`    ${edge.from} --> ${edge.to}`);
  }
  if (machine.terminalStates.length > 0) {
    lines.push("");
    for (const state of machine.terminalStates) {
      lines.push(`    class ${state} terminalState;`);
    }
    lines.push("    classDef terminalState stroke-width:3px;");
  }
  lines.push("```");
  lines.push("");
  lines.push(
    `- **${machine.states.length} states**, **${machine.edges.length} legal transitions** (guarded by \`${machine.guard}\`).`,
  );
  lines.push(
    `- Terminal states: ${machine.terminalStates.map((state) => `\`${state}\``).join(", ") || "none"}.`,
  );
  return lines.join("\n");
}

export const PROGRAMME_GRAPH_BEGIN_MARKER = "<!-- BEGIN GENERATED PROGRAMME GRAPH -->";
export const PROGRAMME_GRAPH_END_MARKER = "<!-- END GENERATED PROGRAMME GRAPH -->";

export function renderProgrammeGraphSection(
  views: Array<MachineView<string>> = buildProgrammeGraphViews(),
): string {
  return [
    PROGRAMME_GRAPH_BEGIN_MARKER,
    "",
    "<!-- Generated by `npm run graph:programme -w @lexi/programme`. Do not edit by hand — edit",
    "     TRANSITIONS in packages/programme/src/*-state-machine.ts and regenerate. -->",
    "",
    views.map(renderMachine).join("\n\n"),
    "",
    PROGRAMME_GRAPH_END_MARKER,
  ].join("\n");
}

export interface ProgrammeGraphSyncResult {
  inSync: boolean;
  reason?: string;
  updatedContent?: string;
}

/**
 * Replaces the marker-delimited region of `markdown` with a freshly generated
 * section. Used both by the generator script (to write) and the drift test
 * (to compare) so the two can never disagree about what "in sync" means.
 */
export function applyProgrammeGraphSection(markdown: string): ProgrammeGraphSyncResult {
  const beginIndex = markdown.indexOf(PROGRAMME_GRAPH_BEGIN_MARKER);
  const endIndex = markdown.indexOf(PROGRAMME_GRAPH_END_MARKER);

  if (beginIndex === -1 || endIndex === -1) {
    return {
      inSync: false,
      reason: `Missing ${PROGRAMME_GRAPH_BEGIN_MARKER} / ${PROGRAMME_GRAPH_END_MARKER} markers.`,
    };
  }
  if (endIndex < beginIndex) {
    return { inSync: false, reason: "Programme graph end marker appears before the begin marker." };
  }

  const before = markdown.slice(0, beginIndex);
  const after = markdown.slice(endIndex + PROGRAMME_GRAPH_END_MARKER.length);
  const updatedContent = `${before}${renderProgrammeGraphSection()}${after}`;

  return {
    inSync: updatedContent === markdown,
    reason:
      updatedContent === markdown
        ? undefined
        : "Generated programme graph differs from the committed doc.",
    updatedContent,
  };
}
